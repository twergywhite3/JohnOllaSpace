/**
 * Recalculates lawmaker composite score based on current formula weights
 */
export function calculateLawmakerScore(
  lawmaker: Lawmaker,
  weights: FormulaWeights,
  totalSittings: number
): number {
  const effectiveTotalSittings = Math.max(totalSittings, 1);
  const attendancePct = Math.min(100, Math.round((lawmaker.sittingsAttended / effectiveTotalSittings) * 100));

  // Normalizations for scoring benchmarks (100-point maximum basis)
  // Attendance score: 0 to 100
  const normAttendance = attendancePct;

  // Motions moved score (target benchmark ~ 12 motions for 100)
  const normMotionsMoved = Math.min(100, (lawmaker.motionsMoved / 10) * 100);

  // Motions supported score (target benchmark ~ 25 motions for 100)
  const normMotionsSupported = Math.min(100, (lawmaker.motionsSupported / 25) * 100);

  // Bills sponsored score (target benchmark ~ 6 bills for 100)
  const normBills = Math.min(100, (lawmaker.billsSponsored / 6) * 100);

  // Debate contributions / Hansard interventions (benchmark ~ 60 interventions for 100)
  const normDebates = Math.min(100, (lawmaker.debateInterventions / 60) * 100);

  // Calculate weighted sum
  const totalWeight =
    weights.attendance +
    weights.motionsMoved +
    weights.motionsSupported +
    weights.bills +
    weights.debateContributions;

  let weightedTotal =
    normAttendance * weights.attendance +
    normMotionsMoved * weights.motionsMoved +
    normMotionsSupported * weights.motionsSupported +
    normBills * weights.bills +
    normDebates * weights.debateContributions;

  // Include custom metrics if available
  if (weights.customMetrics && lawmaker.customMetricScores) {
    for (const [metricId, customWeight] of Object.entries(weights.customMetrics)) {
      const val = lawmaker.customMetricScores[metricId] || 0;
      // normalize using a standard 10-cap
      const normVal = Math.min(100, (val / 8) * 100);
      weightedTotal += normVal * (customWeight * 0.2); // proportional factor
    }
  }

  const finalScore = Number((weightedTotal / totalWeight).toFixed(1));
  return Math.min(99.9, Math.max(20, finalScore));
}
